export const GLYPH_HEIGHT = 7;

const cache = new Map();

/** Bit rows for a character: { w, rows: Uint8Array[] } */
export function glyph(ch) {
  let g = cache.get(ch);
  if (g) return g;
  const src = G[ch] || G[ch.toUpperCase()] || G['?'];
  g = { w: src[0].length, rows: src.map((r) => Uint8Array.from(r, (c) => (c === '#' ? 1 : 0))) };
  cache.set(ch, g);
  return g;
}

/** Width in dots of `text` at `scale`, with one dot of spacing between letters. */
export function measure(text, scale = 1) {
  let w = 0;
  for (const ch of String(text)) w += (glyph(ch).w + 1) * scale;
  return Math.max(0, w - scale);
}
