const cache = new Map();

export function iconSvg(name) {
  const hit = cache.get(name);
  if (hit) return hit;
  const rows = I[name] || I.star;
  let rects = '';
  rows.forEach((r, y) => {
    let x = 0;
    while (x < 8) {
      if (r[x] !== '#') {
        x += 1;
        continue;
      }
      let n = 1;
      while (x + n < 8 && r[x + n] === '#') n += 1;
      rects += `<rect x="${x}" y="${y}" width="${n}" height="1"/>`;
      x += n;
    }
  });
  const svg = `<svg viewBox="-1 -1 10 10" shape-rendering="crispEdges" aria-hidden="true" fill="currentColor">${rects}</svg>`;
  cache.set(name, svg);
  return svg;
}
